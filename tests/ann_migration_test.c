static void TestVirtualAngle(void)
{
    VSG_DEF v = {0};
    float reference = 0.0f, omega;
    unsigned k;
    for(k = 0U; k < 10000U; k++)
    {
        omega = (k % 3U == 0U) ? 0.01f : ((k % 3U == 1U) ? 5.0f : -0.009f);
        if(omega > 0.01f || omega < -0.01f) reference += omega * CONTROL_TS;
        VSG_VirtualAngleStep(&v, omega, CONTROL_TS, true);
        NearAnn(v.virtual_angle_int, reference, 0.0f);
        NearAnn(v.virtual_angle_deg, atan2f(sinf(reference), cosf(reference)) * 57.29577951308232f, 0.0f);
    }
    v.virtual_angle_int = 4.0f;
    VSG_VirtualAngleStep(&v, 0.0f, CONTROL_TS, true);
    assert(v.virtual_angle_rad < 0.0f && v.virtual_angle_deg >= -180.0f);
    VSG_VirtualAngleStep(&v, 1.0f, CONTROL_TS, false);
    assert(v.virtual_angle_int == 0.0f && v.virtual_angle_rad == 0.0f && v.virtual_angle_deg == 0.0f);
    puts("PASS ANN: legacy virtual-angle integral/deadband/wrap; separate from modulation angle");
}

static void TestBackgroundAndApply(void)
{
    unsigned i;
    float hBefore, dBefore;
    InverterSettings_Init();
    AnnAdaptive_Init();
    assert(INV_CMD.ann_enable == 0U && INV_CMD.jd_apply_cmd == 0U && INV_CMD.jd_adapt_enable == 0U);
    hBefore = INV_PARAM.vsg.h;
    dBefore = INV_PARAM.vsg.dp_pu;
    for(i = 0U; i < ANN_AVERAGE_SAMPLES - 1U; i++) AnnAdaptive_Sample(true, 572.6324f, 22.0476f);
    Inverter_Background();
    assert(ANN_CTRL.inference_count == 0U && ANN_CTRL.ann_run_flag == 0U);
    AnnAdaptive_Sample(true, 572.6324f, 22.0476f);
    assert(ANN_CTRL.ann_run_flag == 1U);
    Inverter_Background();
    assert(!irqDisabled && ANN_CTRL.inference_count == 1U && ANN_CTRL.result_valid == 1U);
    NearAnn(ANN_CTRL.ann_Q_input, 572.6324f, 0.002f);
    NearAnn(ANN_CTRL.ann_Angle_input, 22.0476f, 0.00005f);
    NearAnn(ANN_CTRL.L_est, 8.75591469f, 0.0002f);
    NearAnn(INV_PARAM.vsg.h, hBefore, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, dBefore, 0.0f);
    annJdApplyEnable = 0U;
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));
    NearAnn(INV_PARAM.vsg.h, hBefore, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, dBefore, 0.0f);
    annJdApplyEnable = 1U; // Explicitly opt in for application tests; production default stays 0.
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, false, false));
    assert(AnnAdaptive_Apply(&INV_PARAM.vsg, false, true));
    NearAnn(INV_PARAM.vsg.h, ANN_CTRL.J_apt * 0.5f, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, ANN_CTRL.D_apt, 0.0f);
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, false));
    Window(0.0f, 10.0f);
    Inverter_Background();
    assert(AnnAdaptive_Apply(&INV_PARAM.vsg, true, false));
    assert(ANN_CTRL.apply_count == 2U);
    INV_PARAM.vsg.power_loop_div = 65535U;
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, false, true));
    INV_PARAM.vsg.power_loop_div = 1U;
    AnnAdaptive_Sample(false, 0.0f, 0.0f);
    assert(ANN_CTRL.result_valid == 0U && !AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));

    // Invalid predictions publish raw outputs but cannot change controller parameters.
    hBefore = INV_PARAM.vsg.h;
    dBefore = INV_PARAM.vsg.dp_pu;
    Window(-5000.0f, 20.0f);
    Inverter_Background();
    assert(ANN_CTRL.input_in_range == 1U && ANN_CTRL.impedance_in_range == 0U);
    assert(ANN_CTRL.result_valid == 0U && ANN_CTRL.result_status == ANN_RESULT_JD_INVALID);
    {
        float L, R, J, D;
        ANN_ConstV_Predict(ANN_CTRL.ann_Q_input, ANN_CTRL.ann_Angle_input, &L, &R);
        VSG_JD_ANN2_Predict(R, L / 1000.0f, &J, &D);
        NearAnn(ANN_CTRL.L_est, L, 0.00001f);
        NearAnn(ANN_CTRL.R_est, R, 0.00001f);
        NearAnn(ANN_CTRL.J_apt, J, 0.00001f);
        NearAnn(ANN_CTRL.D_apt, D, 0.00001f);
        assert(!(J > 0.0f && D > 0.0f));
    }
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));
    NearAnn(INV_PARAM.vsg.h, hBefore, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, dBefore, 0.0f);
    Window(2000.0f, 40.0f);
    Inverter_Background();
    assert(ANN_CTRL.input_in_range == 0U && ANN_CTRL.result_valid == 1U);
    assert(ANN_CTRL.result_status == ANN_RESULT_VALID);
    NearAnn(ANN_CTRL.L_est, 6.85083914f, 0.0001f);
    NearAnn(ANN_CTRL.R_est, 0.938501239f, 0.00001f);
    assert(AnnAdaptive_Apply(&INV_PARAM.vsg, false, true)); // Out-of-training-domain input is not rejected.
    Window(NAN, 10.0f);
    Inverter_Background();
    assert(ANN_CTRL.result_valid == 0U);
    assert(isnan(ANN_CTRL.R_est) && isnan(ANN_CTRL.L_est) && isnan(ANN_CTRL.J_apt) && isnan(ANN_CTRL.D_apt));
    assert(ANN_CTRL.result_status == ANN_RESULT_INPUT_RANGE);
    assert(ANN_CTRL.has_valid_result == 1U);
    hBefore = INV_PARAM.vsg.h;
    dBefore = INV_PARAM.vsg.dp_pu;
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));
    NearAnn(INV_PARAM.vsg.h, hBefore, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, dBefore, 0.0f);
    Window(969.2444f, 2.6946f); // Legacy golden vector: negative raw R, but finite J/D.
    Inverter_Background();
    assert(ANN_CTRL.result_status == ANN_RESULT_IMPEDANCE_RANGE && ANN_CTRL.result_valid == 0U);
    assert(ANN_CTRL.R_est < 0.0f && isfinite(ANN_CTRL.J_apt) && isfinite(ANN_CTRL.D_apt));
    {
        float L, R, J, D;
        ANN_ConstV_Predict(ANN_CTRL.ann_Q_input, ANN_CTRL.ann_Angle_input, &L, &R);
        VSG_JD_ANN2_Predict(R, L / 1000.0f, &J, &D);
        NearAnn(ANN_CTRL.L_est, L, 0.00001f);
        NearAnn(ANN_CTRL.R_est, R, 0.00001f);
        NearAnn(ANN_CTRL.J_apt, J, 0.00001f);
        NearAnn(ANN_CTRL.D_apt, D, 0.00001f);
    }
    assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));
    NearAnn(INV_PARAM.vsg.h, hBefore, 0.0f);
    NearAnn(INV_PARAM.vsg.dp_pu, dBefore, 0.0f);
    Window(INFINITY, 10.0f);
    Inverter_Background();
    assert(ANN_CTRL.result_status == ANN_RESULT_INPUT_RANGE && isnan(ANN_CTRL.R_est));

    // Latest-wins input mailbox; no partially mixed windows.
    Window(-1000.0f, 15.0f);
    Window(0.0f, 10.0f);
    irqDisabled = true;
    Inverter_Background();
    assert(irqDisabled && ANN_CTRL.ann_run_flag == 1U);
    irqDisabled = false;
    Inverter_Background();
    NearAnn(ANN_CTRL.ann_Q_input, 0.0f, 0.0f);
    assert(ANN_CTRL.result_valid == 1U);

    AnnAdaptive_Init();
    Window(572.6324f, 22.0476f);
    maskCount = 0U;
    cancelDuringInference = true;
    Inverter_Background();
    assert(!irqDisabled && ANN_CTRL.inference_count == 0U && ANN_CTRL.result_valid == 0U);
    assert(ANN_CTRL.ann_run_flag == 1U);
    Inverter_Background();
    assert(ANN_CTRL.inference_count == 1U && ANN_CTRL.result_valid == 1U);
    NearAnn(ANN_CTRL.ann_Q_input, 0.0f, 0.0f);
    puts("PASS ANN: 100-sample background mailbox, J/2->H, manual/auto apply, invalid/Euler checks, stale-session cancellation");
}

static void TestControlIntegration(void)
{
    float hBefore, thetaBefore;
    unsigned k;
    InverterSettings_Init();
    INV_CMD.auto_test_enable = 0U; // This fixture exercises manual ANN application.
    INV_CMD.virtual_angle_mode = 0U; // Preserve the original feature for this legacy integration fixture.
    AnnAdaptive_Init();
    VSG_Init(&VSG_CTRL);
    INV_CTRL.state = INV_GRID_CONNECTED;
    INV_CMD.run_enable = INV_CMD.grid_connect_cmd = INV_CMD.ann_enable = 1U;
    INV_CMD.p_ref = 1.0f;
    gridPllValid = 1U;
    VSG_EnterGrid(&VSG_CTRL, &INV_PARAM.vsg, TWO_PI * 50.0f, -TWO_PI, 155.56f, 0.0f);
    Window(572.6324f, 22.0476f);
    Inverter_Background();
    hBefore = INV_PARAM.vsg.h;
    INV_CMD.jd_apply_cmd = 1U;
    thetaBefore = INV_CTRL.theta = 0.5f;
    Inverter_ControlStep();
    assert(INV_CMD.jd_apply_cmd == 0U && ANN_CTRL.apply_count == 1U);
    assert(INV_PARAM.vsg.h != hBefore && INV_CTRL.state == INV_GRID_CONNECTED);
    NearAnn(INV_CTRL.theta - thetaBefore, INV_CTRL.omega * CONTROL_TS, 0.000001f);
    NearAnn(VSG_CTRL.virtual_angle_int, (fabsf(VSG_CTRL.omega_m) > 0.01f ? VSG_CTRL.omega_m : 0.0f) * CONTROL_TS, 0.0000001f);
    // The frozen -2pi presync correction must NOT enter this virtual angle.
    INV_CMD.jd_adapt_enable = 1U;
    INV_CMD.grid_connect_cmd = 0U;
    Inverter_ControlStep();
    assert(INV_CMD.jd_adapt_enable == 0U && ANN_CTRL.result_valid == 0U);
    assert(VSG_CTRL.virtual_angle_int == 0.0f);
    hBefore = INV_PARAM.vsg.h;
    INV_CMD.jd_apply_cmd = 1U;
    Inverter_ControlStep();
    assert(INV_CMD.jd_apply_cmd == 0U && INV_PARAM.vsg.h == hBefore);
    // No ANN work/parameter changes in VF, irrespective of operator requests.
    for(k = 0U; k < 101U; k++) Inverter_ControlStep();
    assert(ANN_CTRL.ann_run_flag == 0U && INV_PARAM.vsg.h == hBefore);
    puts("PASS ANN: application command consumption, connected-only adaptation, no theta injection, manual-open invalidation");
}

void TestAnnReactiveModels(void)
{
    unsigned mode, i, j, k;
    float L, R, expectedL, expectedR, J, D, angle, V;
    for(mode = 1U; mode <= 2U; mode++)
    {
        for(i = 0U; i < 9U; i++) for(j = 0U; j < 9U; j++)
        {
            angle = -5.0f + 5.0f * (float)i;
            V = -20.0f + 5.0f * (float)j;
            if(mode == 1U) Legacy_ANN_ConstQ_Predict(angle, V, &expectedL, &expectedR);
            else Legacy_ANN_Droop_Predict(angle, V, &expectedL, &expectedR);
            ANN_ImpedancePredict((uint16_t)mode, NAN, angle, V, &L, &R);
            NearAnn(L, expectedL, 0.00001f); NearAnn(R, expectedR, 0.000002f);
        }
        Inverter_Init(); assert(ReactiveControl_Select((uint16_t)mode));
        INV_CTRL.state = INV_GRID_CONNECTED; ReactiveControl_EnterGrid();
        assert(VsgAutoTest_Request(2U)); // Both reactive modes support adaptive experiment B.
        AnnAdaptive_Init();
        for(k = 0U; k < ANN_AVERAGE_SAMPLES; k++) AnnAdaptive_SampleInputs(true, NAN, 15.0f, 2.0f);
        AnnAdaptive_Service();
        ANN_ImpedancePredict((uint16_t)mode, 0.0f, 15.0f, 2.0f, &L, &R);
        VSG_JD_ANN2_Predict(R, L / 1000.0f, &J, &D);
        assert(ANN_CTRL.model_mode == mode && ANN_CTRL.inference_count == 1U);
        NearAnn(ANN_CTRL.ann_V_input, 2.0f, 0.00001f);
        NearAnn(ANN_CTRL.L_est, L, 0.00001f); NearAnn(ANN_CTRL.R_est, R, 0.000002f);
        NearAnn(ANN_CTRL.J_apt, J, 0.00001f); NearAnn(ANN_CTRL.D_apt, D, 0.001f);
        assert(ANN_CTRL.input_in_range == 1U); // Q is irrelevant to voltage-feature models.
        annJdApplyEnable = 1U;
        if(ANN_CTRL.result_valid == 1U && D * CONTROL_TS < 2.0f * J)
        {
            assert(AnnAdaptive_Apply(&INV_PARAM.vsg, true, false));
            NearAnn(INV_PARAM.vsg.h, J * 0.5f, 0.00001f);
            NearAnn(INV_PARAM.vsg.dp_pu, D, 0.001f);
        }
        // A queued result from another mode must not publish or apply after a mode change.
        for(k = 0U; k < ANN_AVERAGE_SAMPLES; k++) AnnAdaptive_SampleInputs(true, 0, 15, 2);
        REACTIVE_CTRL.active_mode = (uint16_t)(3U - mode);
        AnnAdaptive_Service(); assert(ANN_CTRL.inference_count == 1U);
        assert(!AnnAdaptive_Apply(&INV_PARAM.vsg, true, true));
        for(k = 0U; k < ANN_AVERAGE_SAMPLES; k++) AnnAdaptive_SampleInputs(true, 0, 15, 2);
        AnnAdaptive_Service(); assert(ANN_CTRL.inference_count == 2U && ANN_CTRL.model_mode == 3U - mode);
    }
    Inverter_Init();
    puts("PASS ANN reactive: 162 legacy ConstQ/Droop parity vectors, voltage units, mode mailbox cancellation, shared JD and adaptive B");
}

void TestAnnMigration(void)
{
    TestAnnReactiveModels();
    TestLegacyGoldenVectors();
    TestVirtualAngle();
    TestBackgroundAndApply();
    TestControlIntegration();
}
