static bool irqDisabled, cancelDuringInference;
static unsigned maskCount;

bool Interrupt_disableGlobal(void)
{
    bool previous = irqDisabled;
    if(cancelDuringInference && ++maskCount == 2U)
    {
        unsigned i;
        // Simulate ISR exit/re-entry while FP32 background inference was running.
        AnnAdaptive_Sample(false, 0.0f, 0.0f);
        for(i = 0U; i < ANN_AVERAGE_SAMPLES; i++) AnnAdaptive_Sample(true, 0.0f, 10.0f);
        cancelDuringInference = false;
    }
    irqDisabled = true;
    return previous;
}

bool Interrupt_enableGlobal(void)
{
    bool previous = irqDisabled;
    irqDisabled = false;
    return previous;
}

static void NearAnn(float value, float expected, float tolerance)
{
    if(!(fabsf(value - expected) <= tolerance))
    {
        fprintf(stderr, "ANN expected %.9g, got %.9g (tol %.9g)\n", expected, value, tolerance);
        exit(1);
    }
}

static void Window(float Q, float angle)
{
    unsigned i;
    for(i = 0U; i < ANN_AVERAGE_SAMPLES; i++) AnnAdaptive_Sample(true, Q, angle);
}

